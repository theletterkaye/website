/* ---------- time helpers ---------- */
export const parseT = (s) => {
  if (s == null) return null;
  const str = String(s).trim();
  if (!str) return null;
  const m = str.match(/^(?:(\d+):)?(\d{1,2}(?:\.\d+)?)$/);
  if (!m) return null;
  return (m[1] ? parseInt(m[1], 10) * 60 : 0) + parseFloat(m[2]);
};
export const fmtT = (t) => {
  if (t == null || isNaN(t)) return "—";
  const min = Math.floor(t / 60);
  const sec = t - min * 60;
  const s = sec.toFixed(2).padStart(min ? 5 : 0, "0");
  return min ? `${min}:${s}` : s;
};
export const fmtDate = (d) => {
  const [y, m, dd] = d.split("-");
  return `${parseInt(m)}/${parseInt(dd)}/${y.slice(2)}`;
};

