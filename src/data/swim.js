/* ---------- edits ---------- */
const KID_IDS = KIDS.map((k) => k.id);
const EVENT_CODES = EVENTS.map(([code]) => code);
const COURSES = ["SCY", "LCM", "SCM"];

/**
 * Apply one edit to a copy of the data. The page sends edits rather than the
 * whole dataset, so two phones saving around the same time don't overwrite
 * each other's swims. Returns null for anything malformed.
 *
 *   { type: "add",    kid, swim: { event, date, t, course, relay, dq } }
 *   { type: "delete", kid, id }
 *   { type: "champ",  kid, event, value }   (value null clears the override)
 */
export function applyEdit(data, edit) {
  if (!edit || !KID_IDS.includes(edit.kid)) return null;
  const next = structuredClone(data);
  const kid = edit.kid;

  if (edit.type === "add") {
    const w = edit.swim || {};
    const ok = EVENT_CODES.includes(w.event)
      && /^\d{4}-\d{2}-\d{2}$/.test(w.date)
      && typeof w.t === "number" && w.t > 0 && w.t < 3600
      && COURSES.includes(w.course);
    if (!ok) return null;
    next.swims[kid].push({
      id: typeof w.id === "string" ? w.id.slice(0, 40) : `u-${Date.now()}`,
      event: w.event, date: w.date, t: w.t, course: w.course,
      relay: !!w.relay, dq: !!w.dq,
    });
    return next;
  }

  if (edit.type === "delete") {
    next.swims[kid] = next.swims[kid].filter((x) => x.id !== edit.id);
    return next;
  }

  if (edit.type === "champ") {
    if (!EVENT_CODES.includes(edit.event)) return null;
    const v = edit.value;
    if (v == null) delete next.champs[kid][edit.event];
    else if (typeof v === "number" && v > 0 && v < 3600) next.champs[kid][edit.event] = v;
    else return null;
    return next;
  }

  return null;
}
